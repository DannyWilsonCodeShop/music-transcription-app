async function generateTestPDF(data) {
  // Import the updated PDF generation functions
  const { jsPDF } = require('jspdf');
  
  console.log('📄 Generating test PDF with updated generator...');
  
  const doc = new jsPDF();
  
  // Header - Clean and professional
  doc.setFontSize(24);
  doc.setFont('helvetica', 'bold');
  doc.text(data.title, 105, 30, { align: 'center' });
  
  // Key and tempo info
  doc.setFontSize(12);
  doc.setFont('helvetica', 'normal');
  doc.text(`Key: ${data.key} | Tempo: ${data.tempo} BPM | Meter: ${data.timeSignature}`, 105, 45, { align: 'center' });
  
  let yPosition = 70;
  
  // Generate chord chart using updated functions
  if (data.chords && data.chords.length > 0) {
    console.log('🎵 Using updated Nashville Number System format');
    yPosition = generateTestNashvilleChart(doc, data, yPosition);
  } else {
    console.log('🎵 No chord data available');
    doc.setFontSize(12);
    doc.text('No chord data detected', 20, yPosition);
    yPosition += 20;
  }
  
  // Footer
  yPosition += 30;
  if (yPosition > 270) {
    doc.addPage();
    yPosition = 20;
  }
  doc.setFontSize(10);
  doc.setFont('helvetica', 'italic');
  doc.text('Generated by Updated PDF Generator - Clean Nashville Number System Maintained', 105, yPosition, { align: 'center' });
  
  return Buffer.from(doc.output('arraybuffer'));
}

function generateTestNashvilleChart(doc, data, startY) {
  console.log('🎵 Testing updated Nashville Number System format');
  
  doc.setFontSize(16);
  doc.setFont('helvetica', 'bold');
  doc.text('Nashville Number System', 20, startY);
  let yPosition = startY + 25;
  
  // Convert chord changes to measure-based format
  const measures = convertTestChordsToMeasures(data.chords);
  
  // Generate clean 4-measure lines (NO TABLES, NO GRIDS)
  const measuresPerLine = 4;
  const totalLines = Math.ceil(measures.length / measuresPerLine);
  
  for (let lineIndex = 0; lineIndex < totalLines; lineIndex++) {
    // Check for page break
    if (yPosition > 220) {
      doc.addPage();
      yPosition = 30;
    }
    
    // Add phrase label (clean, no clutter)
    if (lineIndex % 2 === 0) {
      yPosition += 8;
      doc.setFontSize(12);
      doc.setFont('helvetica', 'bold');
      doc.text(`Verse ${Math.floor(lineIndex / 2) + 1}:`, 20, yPosition);
      yPosition += 15;
    }
    
    // Get 4 measures for this line
    const lineMeasures = [];
    for (let i = 0; i < measuresPerLine; i++) {
      const measureIndex = lineIndex * measuresPerLine + i;
      if (measureIndex < measures.length) {
        lineMeasures.push(measures[measureIndex]);
      }
    }
    
    // Generate CLEAN Nashville line (NO TABLES)
    generateTestCleanLine(doc, lineMeasures, yPosition);
    yPosition += 30; // Clean spacing between lines
    
    console.log(`✅ Line ${lineIndex + 1}: Clean Nashville format (no tables)`);
  }
  
  return yPosition;
}

function generateTestCleanLine(doc, measures, yPosition) {
  // CLEAN TEXT-BASED LAYOUT (like Amazing Grace)
  const startX = 40;
  const numberSpacing = 60; // Clean spacing between numbers
  
  measures.forEach((measure, index) => {
    if (measure && index < 4) { // Only show 4 measures per line
      const x = startX + (index * numberSpacing);
      
      // Get the Nashville number for this measure
      const nashvilleNumber = measure.nashvilleNumber || '1';
      const isDownbeat = measure.isDownbeat || (index === 0);
      
      // Main Nashville number (clean, large)
      doc.setFontSize(18);
      doc.setFont('helvetica', 'bold');
      
      // Subtle color coding for downbeats
      if (isDownbeat) {
        doc.setTextColor(200, 0, 0); // Subtle red for downbeats
      } else {
        doc.setTextColor(0, 0, 0); // Black for other chords
      }
      
      doc.text(nashvilleNumber, x, yPosition, { align: 'center' });
      
      // Small measure number below (very subtle)
      doc.setFontSize(8);
      doc.setTextColor(150, 150, 150);
      doc.text(`${measure.measureNumber || index + 1}`, x, yPosition + 12, { align: 'center' });
    }
  });
  
  // Reset color
  doc.setTextColor(0, 0, 0);
}

function convertTestChordsToMeasures(chords) {
  if (!chords || chords.length === 0) {
    return [];
  }
  
  const measures = [];
  const measureMap = {};
  
  // Group chords by measure
  chords.forEach(chord => {
    const measureNum = chord.measure || 1;
    
    if (!measureMap[measureNum]) {
      measureMap[measureNum] = {
        measureNumber: measureNum,
        nashvilleNumber: chord.nashvilleNumber || '1',
        isDownbeat: chord.isDownbeat || false,
        startTime: chord.startTime || 0,
        endTime: chord.endTime || 2
      };
    }
  });
  
  // Convert to array format
  Object.keys(measureMap).sort((a, b) => parseInt(a) - parseInt(b)).forEach(measureNum => {
    measures.push(measureMap[measureNum]);
  });
  
  return measures;
}

