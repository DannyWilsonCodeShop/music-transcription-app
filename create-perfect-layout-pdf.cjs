/**
 * Create Perfect Layout PDF matching the Amazing Grace example
 * This replicates the exact format from amazing-grace-enhanced-analysis.pdf
 */

const { generateMockData } = require('./generate-mock-data.cjs');
const fs = require('fs');

async function createPerfectLayoutPDF() {
  console.log('🎵 Creating Perfect Layout PDF (Amazing Grace Style)');
  console.log('===================================================');
  
  // Load jsPDF
  const { jsPDF } = require('jspdf');
  const doc = new jsPDF();
  
  // Generate mock data
  const mockData = generateMockData();
  
  console.log('📊 Using mock data for:', mockData.videoTitle);
  
  let yPosition = 30;
  
  // === HEADER (matching Amazing Grace style) ===
  doc.setFontSize(20);
  doc.setFont('helvetica', 'bold');
  doc.text(mockData.videoTitle, 105, yPosition, { align: 'center' });
  yPosition += 15;
  
  // Key and tempo info
  doc.setFontSize(12);
  doc.setFont('helvetica', 'normal');
  doc.text(`Key: ${mockData.musicalAnalysis.key} | Tempo: ${mockData.musicalAnalysis.bpm} BPM | Meter: ${mockData.musicalAnalysis.timeSignature}`, 105, yPosition, { align: 'center' });
  yPosition += 25;
  
  console.log('✅ Header added in Amazing Grace style');
  
  // === PERFECT LAYOUT SECTION ===
  // Process measures in groups of 4 (like Amazing Grace)
  const measuresPerLine = 4;
  const totalMeasures = Math.min(16, mockData.alignmentData.measureBasedLayout.length); // Show first 16 measures
  
  for (let lineStart = 0; lineStart < totalMeasures; lineStart += measuresPerLine) {
    const lineMeasures = mockData.alignmentData.measureBasedLayout.slice(lineStart, lineStart + measuresPerLine);
    
    // Check for page break
    if (yPosition > 220) {
      doc.addPage();
      yPosition = 30;
    }
    
    // Add verse label every 8 measures
    if (lineStart % 8 === 0) {
      yPosition += 10;
      doc.setFontSize(14);
      doc.setFont('helvetica', 'bold');
      doc.text(`Verse ${Math.floor(lineStart / 8) + 1}`, 20, yPosition);
      yPosition += 15;
    }
    
    // Generate the perfect layout for this line
    generatePerfectMeasureLine(doc, lineMeasures, yPosition);
    yPosition += 35; // Space between lines
    
    console.log(`✅ Line ${Math.floor(lineStart / measuresPerLine) + 1}: Measures ${lineStart + 1}-${Math.min(lineStart + measuresPerLine, totalMeasures)}`);
  }
  
  // === CHORD PROGRESSION SUMMARY ===
  yPosition += 20;
  if (yPosition > 250) {
    doc.addPage();
    yPosition = 30;
  }
  
  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.text('Chord Progression', 20, yPosition);
  yPosition += 15;
  
  const uniqueChords = [...new Set(mockData.chordsData.chords.map(c => c.chord))];
  const nashvilleNumbers = [...new Set(mockData.chordsData.chords.map(c => c.nashvilleNumber))];
  
  doc.setFontSize(12);
  doc.setFont('helvetica', 'normal');
  doc.text(`Chords: ${uniqueChords.join(' - ')}`, 20, yPosition);
  yPosition += 10;
  doc.text(`Nashville Numbers: ${nashvilleNumbers.join(' - ')}`, 20, yPosition);
  
  console.log('✅ Chord progression summary added');
  
  // === FOOTER ===
  yPosition += 30;
  if (yPosition > 270) {
    doc.addPage();
    yPosition = 250;
  }
  
  doc.setFontSize(10);
  doc.setFont('helvetica', 'italic');
  doc.text('Generated by ChordScout - Nashville Number System', 105, yPosition, { align: 'center' });
  
  // Save PDF
  const fileName = 'wheels-bus-with-passing-chords.pdf';
  doc.save(fileName);
  
  console.log(`\n✅ Perfect Layout PDF Created!`);
  console.log(`📄 File: ${fileName}`);
  console.log(`📊 Pages: ${doc.getNumberOfPages()}`);
  console.log(`🎼 Measures: ${totalMeasures}`);
  
  return {
    fileName,
    pages: doc.getNumberOfPages(),
    measures: totalMeasures
  };
}

/**
 * Generate a perfect measure line matching Amazing Grace format with passing chords
 */
function generatePerfectMeasureLine(doc, measures, yPosition) {
  // Define column positions (matching Amazing Grace spacing)
  const columnPositions = [38, 73, 108, 143]; // Exact positions from Amazing Grace
  const chordY = yPosition;
  const lyricsY = yPosition + 12;
  
  measures.forEach((measure, index) => {
    if (index >= 4) return; // Only 4 measures per line
    
    const xPosition = columnPositions[index];
    
    // Get primary chord (downbeat) and passing chords for this measure
    const primaryChord = measure.primaryChord || measure.downbeatChords[0];
    const passingChords = measure.passingChords || [];
    
    // Position PRIMARY CHORD (RED for downbeats)
    if (primaryChord) {
      doc.setTextColor(255, 0, 0); // RED for downbeats
      doc.setFontSize(12);
      doc.setFont('helvetica', 'bold');
      doc.text(primaryChord.nashvilleNumber, xPosition, chordY);
    }
    
    // Position PASSING CHORDS (BLACK) - offset to the right
    if (passingChords.length > 0) {
      doc.setTextColor(0, 0, 0); // BLACK for passing chords
      doc.setFontSize(10);
      doc.setFont('helvetica', 'normal');
      
      // Position passing chords to the right of the primary chord
      passingChords.forEach((passingChord, passIndex) => {
        const passXOffset = xPosition + 15 + (passIndex * 12); // Offset passing chords
        doc.text(passingChord.nashvilleNumber, passXOffset, chordY);
      });
    }
    
    // Reset to black for lyrics
    doc.setTextColor(0, 0, 0);
    
    // Get syllables for this measure and format them properly
    const syllables = measure.syllables.map(s => s.text);
    let lyricsText = '';
    
    if (syllables.length > 0) {
      // Create proper syllable separation like "A-maz-ing Grace"
      lyricsText = formatSyllablesWithHyphens(syllables);
    }
    
    // Position lyrics under chords
    doc.setFontSize(12);
    doc.setFont('helvetica', 'normal');
    doc.text(lyricsText, xPosition, lyricsY);
  });
}

/**
 * Format syllables with proper hyphenation like "A-maz-ing Grace"
 */
function formatSyllablesWithHyphens(syllables) {
  if (syllables.length <= 1) return syllables.join('');
  
  // Group syllables by words
  let result = '';
  let currentWord = '';
  
  syllables.forEach((syllable, index) => {
    // Simple heuristic: if syllable starts with capital or is common word, it's a new word
    const isNewWord = /^[A-Z]/.test(syllable) || 
                     ['the', 'and', 'on', 'go', 'all', 'through'].includes(syllable.toLowerCase());
    
    if (isNewWord && currentWord) {
      // Finish previous word
      result += currentWord + ' ';
      currentWord = syllable;
    } else {
      // Continue current word
      if (currentWord) {
        currentWord += '-' + syllable;
      } else {
        currentWord = syllable;
      }
    }
  });
  
  // Add final word
  result += currentWord;
  
  return result;
}

