/**
 * Create Perfect Layout PDF with Rhythmic Alignment
 * This adds rhythmic positioning based on note values and beat alignment
 */

const { generateMockData } = require('./generate-mock-data.cjs');
const fs = require('fs');

async function createRhythmicLayoutPDF() {
  console.log('🎵 Creating Perfect Layout PDF with Rhythmic Alignment');
  console.log('====================================================');
  
  // Load jsPDF
  const { jsPDF } = require('jspdf');
  const doc = new jsPDF();
  
  // Generate mock data with rhythmic information
  const mockData = generateRhythmicMockData();
  
  console.log('📊 Using rhythmic mock data for:', mockData.videoTitle);
  
  let yPosition = 30;
  
  // === HEADER ===
  doc.setFontSize(20);
  doc.setFont('helvetica', 'bold');
  doc.text(mockData.videoTitle, 105, yPosition, { align: 'center' });
  yPosition += 15;
  
  doc.setFontSize(12);
  doc.setFont('helvetica', 'normal');
  doc.text(`Key: ${mockData.musicalAnalysis.key} | Tempo: ${mockData.musicalAnalysis.bpm} BPM | Meter: ${mockData.musicalAnalysis.timeSignature}`, 105, yPosition, { align: 'center' });
  yPosition += 25;
  
  console.log('✅ Header added');
  
  // === RHYTHMIC LAYOUT SECTION ===
  const totalMeasures = Math.min(16, mockData.alignmentData.measureBasedLayout.length);
  const measuresPerLine = 4;
  
  for (let lineStart = 0; lineStart < totalMeasures; lineStart += measuresPerLine) {
    const lineMeasures = mockData.alignmentData.measureBasedLayout.slice(lineStart, lineStart + measuresPerLine);
    
    // Check for page break
    if (yPosition > 200) {
      doc.addPage();
      yPosition = 30;
    }
    
    // Add verse label
    if (lineStart % 8 === 0) {
      yPosition += 10;
      doc.setFontSize(14);
      doc.setFont('helvetica', 'bold');
      doc.text(`Verse ${Math.floor(lineStart / 8) + 1}`, 20, yPosition);
      yPosition += 15;
    }
    
    // Generate rhythmic layout for this line
    generateRhythmicMeasureLine(doc, lineMeasures, yPosition);
    yPosition += 45; // More space for rhythmic notation
    
    console.log(`✅ Line ${Math.floor(lineStart / measuresPerLine) + 1}: Measures ${lineStart + 1}-${Math.min(lineStart + measuresPerLine, totalMeasures)} with rhythmic alignment`);
  }
  
  // === RHYTHMIC ANALYSIS ===
  yPosition += 20;
  if (yPosition > 250) {
    doc.addPage();
    yPosition = 30;
  }
  
  doc.setFontSize(14);
  doc.setFont('helvetica', 'bold');
  doc.text('Rhythmic Analysis', 20, yPosition);
  yPosition += 15;
  
  doc.setFontSize(12);
  doc.setFont('helvetica', 'normal');
  doc.text('Note Values: ♩ = Quarter Note, ♫ = Eighth Notes, 𝅘𝅥𝅮 = Sixteenth Notes', 20, yPosition);
  yPosition += 10;
  doc.text('Syllables are positioned according to their rhythmic values', 20, yPosition);
  yPosition += 10;
  doc.text('Downbeats (beat 1) are marked in RED', 20, yPosition);
  
  // === FOOTER ===
  yPosition += 30;
  if (yPosition > 270) {
    doc.addPage();
    yPosition = 250;
  }
  
  doc.setFontSize(10);
  doc.setFont('helvetica', 'italic');
  doc.text('Generated by ChordScout - Rhythmic Nashville Number System', 105, yPosition, { align: 'center' });
  
  // Save PDF
  const fileName = 'wheels-bus-rhythmic-layout.pdf';
  doc.save(fileName);
  
  console.log(`\n✅ Rhythmic Layout PDF Created!`);
  console.log(`📄 File: ${fileName}`);
  console.log(`🎼 Features: Rhythmic alignment, beat positioning, note values`);
  
  return {
    fileName,
    pages: doc.getNumberOfPages()
  };
}

